"""Seed ingredient & additive knowledge base.

Scope: identity, technological function, regulatory status and a cautious concern level.
Concern levels follow the methodology in SCORING_METHODOLOGY.md:
  concern  : regulator has banned/restricted it, or a strong regulatory hazard finding exists
  caution  : mandatory warning label in a major jurisdiction, IARC 2B, or consistent
             animal evidence still under study
  neutral  : authorised, no notable signal at normal intake
  beneficial: whole-food ingredient with a well-established nutritional role
Every entry is seeded with verification_status="pending" for editorial review.
"""


def _i(
    slug,
    name,
    category,
    function,
    concern="neutral",
    synonyms=(),
    *,
    e=None,
    flags=(),
    vegan="yes",
    vegetarian="yes",
    halal="no",
    allergen=None,
    fodmap=None,
    summary=None,
    plain=None,
    notes=(),
    sources=(),
    regional=(),
    us_name=None,
):
    if isinstance(concern, (list, tuple)):  # synonyms passed positionally with the default concern level
        concern, synonyms = "neutral", concern
    return {
        "slug": slug,
        "name": name,
        "category": category,
        "function": function,
        "concern_level": concern,
        "synonyms": list(synonyms),
        "e_number": e,
        "flags": list(flags),
        "vegan": vegan,
        "vegetarian": vegetarian,
        "halal_concern": halal,
        "allergen_code": allergen,
        "fodmap": fodmap,
        "concern_summary": summary,
        "plain_language": plain,
        "regulatory_notes": list(notes),
        "source_keys": list(sources),
        "regional_synonyms": list(regional),
        "us_name": us_name,
    }


